@Component({
  selector: 'wysiwyg-emoticons-dialog',
  standalone: true,
  imports: [CommonModule],
  template: `
    <div class="wysiwyg-emoticons-overlay" *ngIf="visible" (click)="close()">
      <div class="wysiwyg-emoticons-dialog" (click)="$event.stopPropagation()">
        <div class="wysiwyg-emoticons-header">
          <span class="wysiwyg-emoticons-title">Emoticons</span>
          <button type="button" class="wysiwyg-emoticons-close" (click)="close()" aria-label="Close">×</button>
        </div>

        <!-- Category tabs -->
        <div class="wysiwyg-emoticons-tabs">
          <button
            *ngFor="let cat of categories"
            type="button"
            class="wysiwyg-emoticons-tab"
            [class.wysiwyg-emoticons-tab--active]="activeCategory === cat.key"
            [attr.title]="cat.label"
            (click)="setCategory(cat.key)">
            {{ cat.icon }}
          </button>
        </div>

        <!-- Emoji grid -->
        <div class="wysiwyg-emoticons-grid">
          <button
            *ngFor="let emoji of currentEmojis"
            type="button"
            class="wysiwyg-emoticons-emoji"
            (click)="selectEmoji(emoji)">
            {{ emoji }}
          </button>
        </div>

        <div class="wysiwyg-emoticons-footer">
          Emoji free by <a href="https://emojione.com" target="_blank" rel="noopener noreferrer">Emoji One</a>
        </div>
      </div>
    </div>
  `,
  styleUrls: ['./emoticons-dialog.component.scss']
})
export class EmoticonsDialogComponent {
  @Input() visible = false;
  @Output() emojiSelected = new EventEmitter<string>();
  @Output() dialogClosed = new EventEmitter<void>();

  categories = EMOJI_CATEGORIES;
  activeCategory = 'smileys';

  get currentEmojis(): string[] {
    return this.categories.find(c => c.key === this.activeCategory)?.emojis ?? [];
  }

  setCategory(key: string): void {
    this.activeCategory = key;
  }

  selectEmoji(emoji: string): void {
    this.emojiSelected.emit(emoji);
    this.close();
  }

  close(): void {
    this.dialogClosed.emit();
  }
}
